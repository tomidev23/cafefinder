    private function seedCafes(array $catalog): Collection
    {
        $areaCoords = ['Batam' => [1.132, 104.04]];
        $cafes = collect();
        foreach ($catalog as $index => $item) {
            $name = $item['name'] ?? null;
            if (! $name) {
                continue;
            }
            $latitude = (float) ($item['lat'] ?? ($areaCoords['Batam'][0] + (($index % 9) - 4) * .0025));
            $longitude = (float) ($item['lng'] ?? ($areaCoords['Batam'][1] + (($index % 7) - 3) * .003));
            $wifi = (int) ($item['wifi'] ?? 4);
            $cafe = Cafe::query()->updateOrCreate(['slug' => Str::slug($name)], [
                'name' => $name,
                'area' => $item['area'] ?? 'Batam',
                'address' => ($item['area'] ?? 'Batam').', Kota Batam, Kepulauan Riau',
                'latitude' => $latitude,
                'longitude' => $longitude,
                'maps_url' => $item['maps_url'] ?? "https://maps.google.com/?q={$latitude},{$longitude}",
                'rating' => is_numeric($item['rating'] ?? null) ? $item['rating'] : 4.8,
                'reviews_count' => (int) ($item['reviewsCount'] ?? 0),
                'wifi_speed' => $item['wifi_speed'] ?? ($wifi >= 5 ? 150 : ($wifi >= 4 ? 100 : 50)),
                'wifi_rating' => $wifi,
                'price_min' => $item['price_min'] ?? 20000,
                'price_max' => $item['price_max'] ?? 45000,
                'coworking' => (bool) ($item['coworking'] ?? false),
                'long_table' => (bool) ($item['long_table'] ?? false),
                'smoking' => (bool) ($item['smoking'] ?? false),
                'mushola' => (bool) ($item['mushola'] ?? false),
                'is_open' => true,
                'note' => $item['note'] ?? $item['review'] ?? null,
                'image' => '/images/cafe-placeholder.svg',
            ]);
            $cafe->update([
                'store_code' => $index === 0
                    ? config('pos.store.code', 'ART-88')
                    : 'CF-'.str_pad((string) $cafe->id, 3, '0', STR_PAD_LEFT),
            ]);
            $cafes->push($cafe);
        }

        return $cafes;
    }

    /** @return array<int, MenuItem> */
    private function seedMenu(Cafe $cafe, array $data): array
    {
        $categories = [];
        foreach ($data['menu']['menuCategories'] as $category) {
            $record = DB::table('menu_categories')->updateOrInsert(
                ['cafe_id' => $cafe->id, 'slug' => $category['id']],
                ['name' => $category['label'], 'updated_at' => now(), 'created_at' => now()],
            );
            $categories[$category['id']] = DB::table('menu_categories')->where('cafe_id', $cafe->id)->where('slug', $category['id'])->value('id');
        }
        $items = [];
        foreach ($data['pos']['posProducts'] as $product) {
            $id = DB::table('menu_items')->insertGetId([
                'cafe_id' => $cafe->id, 'category_id' => $categories[$product['category']] ?? null,
                'name' => $product['name'], 'description' => $product['description'] ?? null,
                'price' => $product['price'], 'image' => '/images/cafe-placeholder.svg',
                'in_stock' => true, 'barista_recommendation' => ($product['badge'] ?? '') === 'Best Seller',
                'serving_temperature' => 'hot', 'created_at' => now(), 'updated_at' => now(),
            ]);
            $items[$product['id']] = $id;
        }

        return $items;
    }

    private function seedTables(Cafe $cafe, array $data): void
    {
        foreach ($data['operations']['tableZones'] as $zone) {
            $zoneId = DB::table('table_zones')->insertGetId(['cafe_id' => $cafe->id, 'name' => $zone['name'], 'description' => $zone['subtitle'] ?? null, 'created_at' => now(), 'updated_at' => now()]);
            $seats = $zone['tables'] ?? $zone['stools'] ?? [];
            foreach ($seats as $table) {
                DB::table('cafe_tables')->insert(['zone_id' => $zoneId, 'table_number' => (string) $table['id'], 'capacity' => $table['capacity'] ?? 1, 'status' => in_array($table['status'] ?? '', ['terisi', 'occupied'], true) ? 'occupied' : 'available', 'qr_active' => (bool) ($table['qrActive'] ?? true), 'created_at' => now(), 'updated_at' => now()]);
            }
        }
    }

    private function seedDevices(Cafe $cafe, array $data): void
    {
        foreach ($data['operations']['connectedDevices'] as $device) {
            DB::table('devices')->insert(['cafe_id' => $cafe->id, 'name' => $device['name'], 'device_type' => $device['role'], 'serial_number' => $device['serial'] ?? null, 'connectivity' => $device['connectivity'] ?? null, 'status' => $device['status'] ?? 'online', 'created_at' => now(), 'updated_at' => now()]);
        }
    }

    private function seedShifts(Cafe $cafe, array $data): void
    {
        $users = User::query()->whereIn('role', ['owner', 'cashier'])->get();
        $shiftId = DB::table('work_shifts')->insertGetId(['cafe_id' => $cafe->id, 'name' => 'Operasional Harian', 'starts_at' => now()->setTime(7, 0), 'ends_at' => now()->setTime(23, 0), 'status' => 'scheduled', 'created_at' => now(), 'updated_at' => now()]);
        foreach ($users as $user) {
            DB::table('shift_assignments')->insert(['shift_id' => $shiftId, 'user_id' => $user->id, 'position' => $user->role === 'owner' ? 'Owner' : 'Kasir', 'attendance_status' => 'scheduled', 'created_at' => now(), 'updated_at' => now()]);
        }
    }

    private function seedReviews(Cafe $cafe, array $data): void
    {
        $userId = User::query()->value('id');
        foreach (array_slice($data['reviews']['reviews'], 0, 20) as $review) {
            DB::table('reviews')->insert(['cafe_id' => $cafe->id, 'user_id' => $userId, 'rating' => $review['rating'], 'category' => $review['category'] ?? null, 'content' => trim($review['text'], '“”'), 'verified' => (bool) ($review['verified'] ?? false), 'helpful_count' => (int) ($review['helpful'] ?? 0), 'published_at' => now(), 'created_at' => now(), 'updated_at' => now()]);
        }
    }

    private function seedOrders(Cafe $cafe, array $menuItems, array $data): void
    {
        $userId = User::query()->value('id');
        $cashierId = User::query()->where('role', 'cashier')->value('id');
        $items = array_values($menuItems);
        if (! $userId || ! $cashierId || ! $items) {
            return;
        }
        $menuItemId = $items[0];
        $orderId = DB::table('orders')->insertGetId(['cafe_id' => $cafe->id, 'user_id' => $userId, 'cashier_id' => $cashierId, 'order_code' => 'SEED-'.Str::upper(Str::random(8)), 'order_type' => 'dine-in', 'status' => 'completed', 'subtotal' => 38000, 'discount_amount' => 0, 'tax_amount' => 3800, 'total_amount' => 41800, 'ordered_at' => now(), 'created_at' => now(), 'updated_at' => now()]);
        DB::table('order_items')->insert(['order_id' => $orderId, 'menu_item_id' => $menuItemId, 'quantity' => 1, 'unit_price' => 38000, 'total_price' => 38000, 'created_at' => now(), 'updated_at' => now()]);
        DB::table('payments')->insert(['order_id' => $orderId, 'method' => 'qris', 'status' => 'paid', 'amount' => 41800, 'paid_at' => now(), 'created_at' => now(), 'updated_at' => now()]);
    }
